import time
from pymycobot.mycobot280 import MyCobot280

# ==============================================================================
# myCobot 280 基本仕様と使い方 チュートリアル
# ==============================================================================

# 【手順1】通信ポートと通信速度（Baud Rate）の設定
# Macの場合、ポート名は "/dev/tty.usbserial-XXXX" のようになります。
PORT = "/dev/tty.usbserial-5A491022661"
BAUD = 115200

def main():
    print("myCobotに接続します...")
    # myCobotオブジェクトの作成
    mc = MyCobot280(PORT, BAUD)

    # ロボットアームの電源をONにする（必須）
    mc.power_on()
    time.sleep(2)  # 起動するまで少し待つ

    print("接続成功！")

    # ==========================================================================
    # 【仕様1】角度制御 (Angle Control)
    # 関節1〜6 の「角度」を直接指定して動かす方法です。
    # 関数: mc.send_angles([J1, J2, J3, J4, J5, J6], 速度(0〜100))
    # メリット: アームがどのように曲がるか予測しやすく、安全です。
    # ==========================================================================
    print("\n--- 角度制御のテスト ---")

    print("ホームポジション（全て0度）へ移動します")
    # [関節1, 関節2, 関節3, 関節4, 関節5, 関節6], 速度(50)
    mc.send_angles([0, 0, 0, 0, 0, 0], 50)
    time.sleep(3) # 動き終わるまで待つ

    # print("第1関節(根元)と第5関節を90度曲げます")
    # mc.send_angles([90, 0, 0, 0, 90, 0], 50)
    # time.sleep(3)


    # ==========================================================================
    # 【仕様2】座標制御 (Coordinate Control)
    # 手先の「X, Y, Zの空間座標」と「Rx, Ry, Rzの姿勢（向き）」を指定して動かす方法です。
    # 関数: mc.send_coords([X, Y, Z, Rx, Ry, Rz], 速度(0〜100), モード)
    #
    # [パラメータ解説]
    # - X, Y, Z : アームの根元を (0,0,0) としたときの手先の位置 (単位: mm)
    # - Rx, Ry, Rz : 手先の向いている角度（オイラー角・度数法）
    # - モード : 0 (非直線補間・最短ルートで動く), 1 (直線補間・まっすぐ動く)
    #
    # メリット: 「この場所(X,Y,Z)に行け！」と命令できるので、今回のような
    # C++空間との連動（影の追従）に必須です。
    # ==========================================================================
    print("\n--- 座標制御のテスト ---")

    # ※座標制御の前には、安全のため適当な姿勢にしておくのが推奨されます
    mc.send_angles([0, 0, 0, 0, 0, 0], 50)
    time.sleep(3)

    # 現在の座標を取得して表示してみる
    coords = mc.get_coords()
    print(f"現在の座標と姿勢: {coords}")

    print("座標を指定して動かします")
    # X=150, Y=0, Z=200 の位置へ移動。手先の向きは Rx=-90, Ry=0, Rz=0
    # 速度50、モード0（非直線）
    # mc.send_coords([100.0, 20.0, 0.0, 0.0, 0.0, 0.0], 50, 0)
    # time.sleep(3)

    # print("少し右(Y軸プラス方向)に平行移動します")
    mc.send_coords([100.0, 30.0, 100.0, 90.0, 0.0, 0.0], 50, 0)
    time.sleep(3)


    # ==========================================================================
    # 【仕様3】安全装置と電源OFF
    # 最後にアームの力を抜き、電源をOFFにします。
    # ==========================================================================
    print("\nテスト終了。初期位置に戻る")
    # モーターのトルク（保持力）を解除してダラーンとさせる（手で動かせるようになる）
    # mc.release_all_servos()
    mc.send_angles([0, 0, 0, 0, 0, 0], 50)



    # 電源OFF
    # mc.power_off()

if __name__ == "__main__":
    main()
